  ...people.map(([name, simplified]) => ({ type: "PERSON", name, aliases: simplified && simplified !== name ? [simplified] : [], summary: `${simplified || name}，十二本纪相关人物。`, details: "本条目由全文实体识别词典自动建立，生平与出处有待进一步校订。" })),
