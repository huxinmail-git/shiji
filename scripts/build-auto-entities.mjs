const geojson = JSON.parse(fs.readFileSync("public/data/qin-east.geojson", "utf8"));
const placeMap = new Map();
for (const feature of geojson.features) {
  if (feature.geometry.type !== "Point" || !feature.properties.name) continue;
  const [longitude, latitude] = feature.geometry.coordinates;
  placeMap.set(feature.properties.name, { name: feature.properties.name, aliases: [], latitude, longitude });
}
for (const [name, longitude, latitude] of extraPlaces) placeMap.set(name, { name, aliases: [], latitude, longitude });

